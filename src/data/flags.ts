/** Derives the flag emoji from a 2-letter ISO code. "FR" -> 🇫🇷. */
export function flagEmoji(a2: string): string {
  const c = a2.toUpperCase();
  return String.fromCodePoint(
    RI_BASE + (c.charCodeAt(0) - 65),
    RI_BASE + (c.charCodeAt(1) - 65),
  );
}

/** The two regional-indicator code points, e.g. "U+1F1EB U+1F1F7". */
export function flagCodePoints(a2: string): string {
  const c = a2.toUpperCase();
  const cp1 = RI_BASE + (c.charCodeAt(0) - 65);
  const cp2 = RI_BASE + (c.charCodeAt(1) - 65);
  return `U+${cp1.toString(16).toUpperCase()} U+${cp2.toString(16).toUpperCase()}`;
}

export const FLAG_REGIONS = ["Africa", "Americas", "Asia", "Europe", "Oceania", "Antarctica"] as const;

export function flagsByRegion(region: string): Flag[] {
  return FLAGS.filter(f => f.region === region);
}
