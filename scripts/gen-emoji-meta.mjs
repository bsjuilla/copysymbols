// Generates src/data/emoji-meta.ts — per-emoji Unicode/Emoji version + release
// year (from the official unicode.org emoji-test.txt E-markers) and official
// CLDR English keywords. Keys are the EXACT glyph strings used in
// src/data/emoji.ts; matching is done FE0F-insensitive.
//
// Inputs (downloaded beforehand):
//   /tmp/unidata/emoji-test.txt   — unicode.org/Public/emoji/16.0/emoji-test.txt
//   /tmp/unidata/annotations.json — CLDR cldr-annotations-full en
import { readFileSync, writeFileSync } from "node:fs";

const strip = (s) => s.replace(/️/g, "");

// Emoji-version → release year (standard Unicode/Emojipedia mapping).
const YEAR = {
  "0.6": 2010, "0.7": 2014, "1.0": 2015, "2.0": 2015, "3.0": 2016,
  "4.0": 2016, "5.0": 2017, "11.0": 2018, "12.0": 2019, "12.1": 2019,
  "13.0": 2020, "13.1": 2020, "14.0": 2021, "15.0": 2022, "15.1": 2023,
  "16.0": 2024,
};

// 1) glyphs from src/data/emoji.ts (exact strings, in site order)
const emojiTs = readFileSync("src/data/emoji.ts", "utf8");
const glyphs = [...emojiTs.matchAll(/emoji: "([^"]+)"/g)].map((m) => m[1]);
console.log(`site emoji: ${glyphs.length}`);

// 2) emoji-test.txt → stripped glyph → E-version
const vMap = new Map();
for (const line of readFileSync("/tmp/unidata/emoji-test.txt", "utf8").split("\n")) {
  const m = line.match(/^[0-9A-F ]+;\s*(fully-qualified|component)\s*#\s*(\S+)\s+E(\d+\.\d+)\s/);
  if (!m) continue;
  const key = strip(m[2]);
  if (!vMap.has(key)) vMap.set(key, m[3]);
}
console.log(`emoji-test versions parsed: ${vMap.size}`);

// 3) CLDR annotations → stripped glyph → keywords
const cldr = JSON.parse(readFileSync("/tmp/unidata/annotations.json", "utf8"));
const ann = cldr.annotations.annotations;
const kwMap = new Map();
for (const [g, v] of Object.entries(ann)) {
  if (v.default) kwMap.set(strip(g), v.default);
}
console.log(`CLDR annotation entries: ${kwMap.size}`);

// 4) join
let haveV = 0, haveK = 0;
const entries = [];
for (const g of glyphs) {
  const k = strip(g);
  const v = vMap.get(k);
  const kws = kwMap.get(k);
  if (v) haveV++;
  if (kws) haveK++;
  if (!v && !kws) continue;
  const year = v ? YEAR[v] : undefined;
  const kwOut = (kws ?? []).slice(0, 8).map((s) => s.replaceAll('"', "'"));
  entries.push(
    `  ${JSON.stringify(g)}: { v: ${JSON.stringify(v ?? "")}, y: ${year ?? 0}, kw: ${JSON.stringify(kwOut)} },`
  );
}
console.log(`coverage: version ${haveV}/${glyphs.length}, keywords ${haveK}/${glyphs.length}`);

const out = `// GENERATED by scripts/gen-emoji-meta.mjs — do not edit by hand.
// Sources: unicode.org emoji-test.txt v16.0 (E-version markers) + Unicode CLDR
// English annotations (official keywords). Keys are the exact glyph strings in
// src/data/emoji.ts. v = Emoji spec version ("" = unknown), y = release year
// (0 = unknown), kw = official CLDR keywords (max 8).
// Server-only: import from server components; do NOT pass wholesale to client.

export interface EmojiMeta { v: string; y: number; kw: string[] }

const STRIP_VS = /\\uFE0F/g;

export const EMOJI_META: Record<string, EmojiMeta> = {
${entries.join("\n")}
};

const _byStripped = new Map<string, EmojiMeta>();
for (const [g, m] of Object.entries(EMOJI_META)) _byStripped.set(g.replace(STRIP_VS, ""), m);

export function getEmojiMeta(glyph: string): EmojiMeta | undefined {
  return EMOJI_META[glyph] ?? _byStripped.get(glyph.replace(STRIP_VS, ""));
}
`;
writeFileSync("src/data/emoji-meta.ts", out, "utf8");
console.log(`wrote src/data/emoji-meta.ts (${entries.length} entries, ${out.length} bytes)`);
