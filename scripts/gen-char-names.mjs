// Generates src/data/char-names.ts — official Unicode character names for every
// distinct codepoint used in the site's kaomoji faces (the "anatomy" data for
// /kaomoji/[slug]). Only the codepoints actually used are emitted (small file).
//
// Input: /tmp/unidata/UnicodeData.txt (unicode.org/Public/UNIDATA/UnicodeData.txt)
import { readFileSync, writeFileSync } from "node:fs";

// 1) collect distinct codepoints from all kaomoji faces
const files = ["src/data/kaomoji.ts", "src/data/kaomoji-extra.ts", "src/data/generated-kaomoji.ts"];
const cps = new Set();
let faces = 0;
for (const f of files) {
  const src = readFileSync(f, "utf8");
  for (const m of src.matchAll(/face: "((?:[^"\\]|\\.)*)"/g)) {
    faces++;
    // JSON-parse to resolve \\ escapes (e.g. shrug's backslash)
    let face;
    try { face = JSON.parse(`"${m[1]}"`); } catch { face = m[1]; }
    for (const ch of face) cps.add(ch.codePointAt(0));
  }
}
console.log(`faces scanned: ${faces}, distinct codepoints: ${cps.size}`);

// 2) UnicodeData.txt → codepoint → official name (field 1; field 10 = Unicode 1.0
//    name, used as fallback for control-ish entries)
const names = new Map();
for (const line of readFileSync("/tmp/unidata/UnicodeData.txt", "utf8").split("\n")) {
  const parts = line.split(";");
  if (parts.length < 11) continue;
  const cp = parseInt(parts[0], 16);
  if (!cps.has(cp)) continue;
  let name = parts[1];
  if (name.startsWith("<")) name = parts[10] || name;
  names.set(cp, name);
}

// 3) report misses (e.g. chars inside First/Last ranges — name them generically)
const missing = [...cps].filter((c) => !names.has(c)).sort((a, b) => a - b);
for (const c of missing) {
  // All kaomoji chars are individually listed in UnicodeData except CJK/Hangul
  // range members; give those their standard algorithmic names.
  if (c >= 0x4e00 && c <= 0x9fff) names.set(c, `CJK UNIFIED IDEOGRAPH-${c.toString(16).toUpperCase()}`);
  else if (c >= 0xac00 && c <= 0xd7a3) names.set(c, `HANGUL SYLLABLE-${c.toString(16).toUpperCase()}`);
  else names.set(c, `U+${c.toString(16).toUpperCase().padStart(4, "0")}`);
}
console.log(`named: ${names.size}/${cps.size} (${missing.length} via range fallback: ${missing.map((c) => "U+" + c.toString(16).toUpperCase()).join(" ") || "none"})`);

// 4) emit, sorted by codepoint
const entries = [...names.entries()].sort((a, b) => a[0] - b[0])
  .map(([cp, n]) => `  0x${cp.toString(16).toUpperCase()}: ${JSON.stringify(n)},`);

const out = `// GENERATED by scripts/gen-char-names.mjs — do not edit by hand.
// Official Unicode character names (UnicodeData.txt) for every distinct
// codepoint used in the site's kaomoji faces. Powers the per-character
// "anatomy" breakdown on /kaomoji/[slug]. Server-only.

export const CHAR_NAMES: Record<number, string> = {
${entries.join("\n")}
};

/** Official name in Title Case (e.g. "Latin Small Letter Turned V"). */
export function charName(cp: number): string {
  const raw = CHAR_NAMES[cp];
  if (!raw) return "U+" + cp.toString(16).toUpperCase().padStart(4, "0");
  return raw
    .toLowerCase()
    .replace(/(^|[\\s(-])([a-z])/g, (m, pre, ch) => pre + ch.toUpperCase());
}
`;
writeFileSync("src/data/char-names.ts", out, "utf8");
console.log(`wrote src/data/char-names.ts (${entries.length} entries, ${out.length} bytes)`);
